echo ""
echo "   [액션 1] URL 가져오기"
echo "   ────────────────────────────"
echo "   • 검색창에 'URL' 입력"
echo "   • 'URL 가져오기' 선택"
echo "   • URL 입력: http://192.168.219.1:8800/speaker_2.wav"
echo "   • (Mac IP는 자동으로 감지됩니다)"
echo ""
echo "   [액션 2] URL 콘텐츠 가져오기" 
echo "   ────────────────────────────"
echo "   • 검색창에 'URL 콘텐츠' 입력"
echo "   • 'URL 콘텐츠 가져오기' 선택"
echo "   • 입력: 이전 액션의 URL"
echo ""
echo "   [액션 3] 미디어 재생"
echo "   ────────────────────────────"
echo "   • 검색창에 '미디어 재생' 입력"
echo "   • '미디어 재생' 선택"
echo "   • 입력: 이전 액션의 콘텐츠"
echo ""
echo "4단계: 단축어 이름 설정"
echo "   • 상단의 '새로운 단축어' 클릭"
