# Mac의 로컬 IP 찾기
MAC_IP=$(ipconfig getifaddr en0 || ipconfig getifaddr en1)

if [ -z "$MAC_IP" ]; then
    echo "⚠️  Mac IP를 찾을 수 없습니다. Wi-Fi에 연결되어 있는지 확인하세요."
else
    echo "✅ Mac IP: $MAC_IP"
    echo ""
    echo "Shortcuts URL을 다음으로 변경하세요:"
    echo "http://${MAC_IP}:8800/speaker_2.wav"
fi

